/** lang の文言（無い言語は en・無いキーはキーそのもの）。{name} を vars の値で 1 回だけ置き換える */
export function updateText(lang: string | undefined, key: string, vars: Record<string, string> = {}): string {
  const table = (lang && UPDATE_MESSAGES[lang]) || UPDATE_MESSAGES.en;
  const text = (table as Record<string, string>)[key] ?? (UPDATE_MESSAGES.en as Record<string, string>)[key] ?? key;
  return text.replace(/\{([a-z]+)\}/g, (whole, name: string) => (Object.prototype.hasOwnProperty.call(vars, name) ? vars[name] : whole));
}
